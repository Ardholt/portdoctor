import { existsSync, mkdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { scanDir } from './scan.ts';
import { groupFindings } from './group.ts';
import type { ScanResult } from './types.ts';

// Variants as recalled from public QNX docs (qcc -V<name>). Recalled, not checked against an SDP.
const ARCH: Record<string, { variant: string; proc: string }> = {
  aarch64le: { variant: 'gcc_ntoaarch64le', proc: 'aarch64' },
  x86_64: { variant: 'gcc_ntox86_64', proc: 'x86_64' },
};

export function toolchainCmake(arch: string): string {
  const a = ARCH[arch];
  if (!a) throw new Error(`--arch must be one of ${Object.keys(ARCH).join(', ')}`);
  return `# qnx-toolchain.cmake, generated by portdoctor init-toolchain (skeleton).
# Facts used (recalled from public QNX/CMake documentation, NOT verified against an SDP; check them):
#   - CMake supports CMAKE_SYSTEM_NAME QNX and drives the SDP compilers qcc (C) and q++ (C++)
#   - the target is chosen with qcc -V<variant>; for this arch the variant is ${a.variant}
#   - QNX_HOST and QNX_TARGET are set by sourcing the SDP's qnxsdp-env.sh
# Usage: source <sdp>/qnxsdp-env.sh && cmake -S . -B build-qnx -DCMAKE_TOOLCHAIN_FILE=qnx-toolchain.cmake

if(NOT DEFINED ENV{QNX_HOST} OR NOT DEFINED ENV{QNX_TARGET})
  message(FATAL_ERROR "QNX_HOST/QNX_TARGET not set: source the SDP's qnxsdp-env.sh first")
endif()

set(CMAKE_SYSTEM_NAME QNX)
set(CMAKE_SYSTEM_PROCESSOR ${a.proc})

set(CMAKE_C_COMPILER qcc)
set(CMAKE_CXX_COMPILER q++)
set(CMAKE_C_COMPILER_TARGET ${a.variant})
set(CMAKE_CXX_COMPILER_TARGET ${a.variant})
# If your CMake does not turn *_COMPILER_TARGET into -V<variant>, use this instead:
# set(CMAKE_C_FLAGS_INIT "-V${a.variant}")
# set(CMAKE_CXX_FLAGS_INIT "-V${a.variant}")

set(CMAKE_FIND_ROOT_PATH $ENV{QNX_TARGET})
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
`;
}

const clean = (s: string) => s.replace(/\*\//g, '* /').replace(/\n/g, ' ');

export function portabilityHeader(res: ScanResult | null): string {
  const L = [
    '/* portability.h: skeleton generated by `portdoctor init-toolchain`.',
    ' * Nothing here was compiled against a QNX SDP. It lists what the scan flagged, with TODOs; it defines no QNX API',
    ' * because that needs the SDP headers. Fill each TODO after checking the SDP, then include this header where needed. */',
    '#ifndef PORTABILITY_H',
    '#define PORTABILITY_H',
    '',
    '#if defined(__QNXNTO__)',
    '',
  ];
  if (!res || !res.findings.length) L.push('/* No flagged APIs (or no project scanned). Run: portdoctor init-toolchain <project-dir> */', '');
  else {
    const shims = new Map<string, string>(); // intentionally empty: no shim is invented without SDP headers
    for (const g of groupFindings(res)) {
      if (g.category === 'build' || g.severity === 'info') continue;
      const r = g.rule;
      L.push(`/* ${g.ruleId}: ${clean(g.title)} [${g.severity}, ${g.confidence}${g.confidence === 'guess' ? ': verify against SDP' : g.confidence.startsWith('verified') ? ': ' + g.confidence + ' on SDP' : ''}], ${g.sites.length} site(s) in ${g.files.length} file(s)`);
      if (r) L.push(` * Remedy: ${clean(r.remedy)}`);
      if (r?.verify) L.push(` * ${clean(r.verify)}`);
      L.push(' * TODO: decide the approach and implement a wrapper here. Sites:');
      for (const i of g.sites.slice(0, 5)) L.push(` *   ${res.findings[i].file}:${res.findings[i].line}`);
      if (g.sites.length > 5) L.push(` *   ... and ${g.sites.length - 5} more`);
      L.push(' */');
      const shim = shims.get(g.ruleId);
      if (shim) L.push(shim);
      L.push('');
    }
  }
  L.push('#endif /* __QNXNTO__ */', '', '#endif /* PORTABILITY_H */', '');
  return L.join('\n');
}

export async function runInit(argv: string[]): Promise<number> {
  const args = argv.slice();
  const take = (n: string) => {
    const i = args.indexOf(n);
    if (i < 0) return undefined;
    const v = args[i + 1];
    if (v === undefined) throw new Error(`${n} needs a value`);
    args.splice(i, 2);
    return v;
  };
  const arch = take('--arch') ?? 'aarch64le';
  const outDir = resolve(take('--out') ?? '.');
  const force = args.includes('--force');
  if (force) args.splice(args.indexOf('--force'), 1);
  const dir = args.shift();
  if (args.length) throw new Error('usage: portdoctor init-toolchain [<project-dir>] [--arch aarch64le|x86_64] [--out <dir>] [--force]');
  let res: ScanResult | null = null;
  if (dir) {
    if (!existsSync(dir) || !statSync(dir).isDirectory()) throw new Error(`not a directory: ${dir}`);
    res = scanDir(dir);
  }
  const files: Array<[string, string]> = [
    ['qnx-toolchain.cmake', toolchainCmake(arch)],
    ['portability.h', portabilityHeader(res)],
  ];
  mkdirSync(outDir, { recursive: true });
  for (const [n] of files) if (!force && existsSync(join(outDir, n))) throw new Error(`${join(outDir, n)} exists; use --force to overwrite`);
  for (const [n, t] of files) {
    writeFileSync(join(outDir, n), t);
    process.stdout.write(`wrote ${join(outDir, n)}\n`);
  }
  process.stdout.write('Neither file was tested against a QNX SDP.\n');
  return 0;
}
